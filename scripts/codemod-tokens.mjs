#!/usr/bin/env node
/**
 * Token codemod.
 *
 * Phase A rules only rename utilities whose replacement resolves to a
 * bit-identical computed value (the compat aliases in styles/tokens.css were
 * chosen to guarantee this). Running phase A must produce zero visual change;
 * that is the whole point, and it is what makes ~900 edits safe to land at once.
 *
 * Phase B rules are deliberate consolidations — the long tail of one-off
 * opacities, the radius scale, and the mono-to-sans switch. They DO change
 * pixels, on purpose.
 *
 *   node scripts/codemod-tokens.mjs --phase a [--dry]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const args = process.argv.slice(2);
const DRY = args.includes('--dry');
const phase = (args[args.indexOf('--phase') + 1] || 'a').toLowerCase();

// Vendored registry components are regenerated by `shadcn add`; editing them
// here would be reverted on the next update.
const VENDORED = new Set([
  'alert-dialog', 'avatar', 'badge', 'button', 'card', 'checkbox', 'command',
  'context-menu', 'dialog', 'dropdown-menu', 'input', 'input-group', 'label',
  'pill', 'popover', 'scroll-area', 'select', 'separator', 'sheet', 'skeleton',
  'sonner', 'tabs', 'textarea', 'tooltip',
].map((n) => `src/components/ui/${n}.jsx`));

const SKIP_PREFIX = [
  'src/components/__snapshots__/',
  'src/components/ui/CustomIcon.jsx',
  // The token source itself. The compat block literally contains
  // `--color-zinc-500: …` and `--text-fluid-3xs: …`; these rules would match
  // inside those declarations and rewrite the definitions out from under the
  // codemod. Removing them is a deliberate final step, not a rename.
  'src/styles/tokens.css',
  // extendTailwindMerge registers the fluid class names as strings. Renaming
  // them to `text-xs` would duplicate a built-in tw-merge group. Cleaned up by
  // hand once the fluid utilities are gone.
  'src/lib/utils.js',
];

// `end` guards against `-zinc-50` also matching inside `-zinc-500`.
const end = '(?![\\w./-])';
const p = (s) => new RegExp(s + end, 'g');

const PHASE_A = [
  // --- text ramp. Values match the compat aliases exactly. ---
  [p('-zinc-50'), '-foreground'],
  [p('-zinc-100'), '-foreground'],
  [p('-zinc-200'), '-foreground'],
  [p('-zinc-300'), '-foreground-secondary'],
  [p('-zinc-400'), '-muted-foreground'],
  [p('-zinc-500'), '-muted-foreground'],
  [p('-zinc-600'), '-subtle-foreground'],
  [p('-zinc-700'), '-faint-foreground'],
  [p('-zinc-800'), '-secondary'],
  [p('-zinc-900'), '-card'],
  [p('-zinc-950'), '-background'],

  // --- lines and overlays. white is oklch(1 0 0), so these are identical. ---
  [p('border-white/5'), 'border-border-subtle'],
  [p('border-white/10'), 'border-border'],
  [p('border-white/20'), 'border-border-strong'],
  [p('bg-white/5'), 'bg-overlay-subtle'],
  [p('bg-white/10'), 'bg-overlay'],
  [p('bg-white/20'), 'bg-overlay-strong'],
  [p('ring-white/20'), 'ring-overlay-strong'],

  // --- fluid type. Both aliases already resolve to 0.75rem. ---
  [p('text-fluid-3xs'), 'text-xs'],
  [p('text-fluid-2xs'), 'text-xs'],
  [p('text-fluid-xs'), 'text-xs'],
  [p('text-fluid-sm'), 'text-sm'],
  [p('text-fluid-base'), 'text-base'],
  [p('text-fluid-lg'), 'text-lg'],
  [p('text-fluid-xl'), 'text-xl'],
  [p('text-fluid-2xl'), 'text-2xl'],
  [p('text-fluid-3xl'), 'text-3xl'],
];

const RULES = { a: PHASE_A }[phase];
if (!RULES) {
  console.error(`Unknown phase "${phase}".`);
  process.exit(1);
}

const files = execSync('git ls-files "src/**/*.jsx" "src/**/*.js" "src/**/*.css"', { encoding: 'utf8' })
  .split('\n').filter(Boolean)
  .filter((f) => !SKIP_PREFIX.some((s) => f.startsWith(s)))
  .filter((f) => !VENDORED.has(f));

let touched = 0;
const perRule = new Map();

for (const file of files) {
  let src;
  try { src = readFileSync(file, 'utf8'); } catch { continue; }
  const before = src;
  for (const [re, to] of RULES) {
    src = src.replace(re, (m) => {
      perRule.set(re.source, (perRule.get(re.source) || 0) + 1);
      return to;
    });
  }
  if (src !== before) {
    touched++;
    if (!DRY) writeFileSync(file, src);
  }
}

console.log(`\n  Phase ${phase.toUpperCase()}${DRY ? ' (dry run)' : ''}\n`);
let total = 0;
for (const [rule, n] of [...perRule.entries()].sort((a, b) => b[1] - a[1])) {
  console.log(`    ${String(n).padStart(4)}  ${rule.replace(/\(\?!.*$/, '')}`);
  total += n;
}
console.log(`    ${'-'.repeat(4)}`);
console.log(`    ${String(total).padStart(4)}  replacements across ${touched} files\n`);
